export function parseMatchCode(code) {
  const m = code.match(/^([A-Za-z]+)(\d)v([A-Za-z]+)(\d)r([A-Za-z]+)(\d)$/)
  if (!m) return null
  return {
    a: `${m[1]}${m[2]}`,
    b: `${m[3]}${m[4]}`,
    ref: `${m[5]}${m[6]}`,
  }
}
